// Special characters written as escape sequences, so that every source file stays pure ASCII.
// (Copying files through some phones/apps can corrupt non-ASCII characters; escapes cannot be corrupted.)
export const DOT = '\u00b7'        // middle dot
export const TIMES = '\u00d7'      // multiplication sign
export const DASH = '\u2014'       // long dash
export const ELLIPSIS = '\u2026'   // ...
export const ARROW = '\u2192'      // right arrow
export const BULLET = '\u2022'
